-- Vietnam bank reference codes (Napas/BIN-style) for payout metadata.
-- Safe to re-run: upserts on `code`.
-- Run against your GoldPay MySQL database (e.g. pg_service).

CREATE TABLE IF NOT EXISTS `vietnam_bank_codes` (
  `id` int NOT NULL AUTO_INCREMENT,
  `code` varchar(16) NOT NULL,
  `full_name` varchar(512) NOT NULL,
  `abbreviation` varchar(64) NOT NULL,
  `created_at` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (`id`),
  UNIQUE KEY `UQ_vietnam_bank_codes_code` (`code`),
  KEY `IDX_vietnam_bank_codes_abbreviation` (`abbreviation`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

